-- S9 阶段三补丁：通知要携带"同意后授予什么"。
--
-- ⚠️ **为什么加这一列。** 邀请进账本时，邀请人可以选择对方是 `editor` 还是 `viewer`
-- （所有者："所有者可以指定对方是 viewer 还是 editor"）。这个"打算授予什么"必须**跟着邀请走**——
-- 否则在对方点"同意"的那一刻，服务端没有别的办法知道该给什么角色，只能硬编码一个默认值。
--
-- ⚠️ **硬编码 `editor` 的后果不是"少一个功能"，而是权限被静默放大**：
-- 邀请人明明选的是"仅查看"，对方拿到的是"可编辑"，而且**两边都以为自己的理解是对的**。
-- 这类"参数被接受、被忽略、被替换成默认值"的失败，正是 `教训.md` §3.2 记的那一类。
--
-- ⚠️ **可重复执行**：`ADD COLUMN IF NOT EXISTS` 本身幂等，没有一条 DELETE。
-- 列可空，所以已有的通知（包括 dev 库里可能存在的）保持 `NULL`，
-- 而**读不到 payload 时 `decideNotification` 会退回 `editor`**——与今天的行为完全一致，
-- 不会因为这次迁移让任何一条旧通知变得无法处理。

ALTER TABLE "notifications"
  ADD COLUMN IF NOT EXISTS "payload" JSONB;
