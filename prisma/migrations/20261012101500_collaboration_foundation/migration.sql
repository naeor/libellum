-- S9 阶段一：协作与多账本的地基（只加字段，不改行为）
--
-- ⚠️ **这个迁移刻意只做"加列 + 修数据"，不动任何现有接口的行为。**
-- 所有者定的顺序是「先数据隔离与权限，再允许真实多账本操作」，所以阶段一的
-- 验收标准是**现有功能一点都不能变**——它是这一轮最重要的回归线。
--
-- ⚠️ **可重复执行**：每条语句都能跑第二遍而不报错。
-- 项目在这件事上付过代价（回退代码时删了迁移文件，库里留下一条"目录已不存在的迁移"，
-- 下一次迁移无法诚实前进，见 ROADMAP 的风险登记册 #13）。
--
-- ⚠️ **失败不留垃圾**：这个文件里没有一条 DELETE。最坏的结果是"列加上了、角色改成了 editor"，
-- 两者都是安全方向（比 owner 更保守），可以人工重跑。

-- ---------------------------------------------------------------------------
-- 1. `users.last_book_id` —— "上次使用的那本账"
-- ---------------------------------------------------------------------------
--
-- 设计里定的是"服务器保存上次使用的账本，登录直接进它的明细页展示态"。
-- 所以它属于**账号的偏好**，存在 users 上，而不是留在某台设备的本地存储里——
-- 这样换一台设备登录，也会回到他上次看的那本账。
--
-- ⚠️ **允许为空**（不回填）：空值的含义是"还没选过"，应用层按"最早加入的那本"兜底即可。
-- 回填需要一个 UUID 字面量，而把某个人的账号 id 写进迁移文件既难看又难维护；
-- 让应用在第一次读取时记住，效果完全一样，而且**不需要在这里猜任何人**。
--
-- ⚠️ `ON DELETE SET NULL`：这本账真被删掉时，"上次用的账本"应该是空，而不是阻止删除。

ALTER TABLE "users"
  ADD COLUMN IF NOT EXISTS "last_book_id" UUID;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'users_last_book_id_fkey'
  ) THEN
    ALTER TABLE "users"
      ADD CONSTRAINT "users_last_book_id_fkey"
      FOREIGN KEY ("last_book_id") REFERENCES "books"("id")
      ON DELETE SET NULL ON UPDATE CASCADE;
  END IF;
END $$;

-- ---------------------------------------------------------------------------
-- 2. `books.disposed_at` —— "整本弃置"
-- ---------------------------------------------------------------------------
--
-- ⚠️ **用词是所有者定的：叫"弃置"，不叫"归档"。**
-- 它的语义是：**服务器保留全部数据**（行不动、不软删除），只是标记这本账被弃置了；
-- **客户端删除本机数据**，普通用户再也看不到它。
--
-- ⚠️ **为什么不加 `deleted_at`**：弃置 ≠ 删除。用 `deleted_at` 会让"这本账还在不在"
-- 与"账目是否被删"混成同一个字段，而这两件事的回答完全不同。
--
-- ⚠️ **"整本弃置"与"我不想再显示这本账"是两件事**，所以后者放在 `book_members.left_at`
-- （见下一节），不放在这里。所有者明确要求把两种语义分开。

ALTER TABLE "books"
  ADD COLUMN IF NOT EXISTS "disposed_at" TIMESTAMPTZ(6);

-- 首页只列"未弃置"的账本，这是那条查询的索引。
CREATE INDEX IF NOT EXISTS "books_disposed_at_idx" ON "books"("disposed_at");

-- ---------------------------------------------------------------------------
-- 3. `book_members.left_at` —— "退出这本账"（只影响我自己）
-- ---------------------------------------------------------------------------
--
-- 语义（所有者定的）：**我只失去访问权，账本对其他人照常存在**，
-- 而且**我的客户端不再显示这本账、也不再存它在本机的信息**，但其他人毫无影响。
--
-- ⚠️ **不删这一行**：账本里"谁曾经参与过"是有价值的历史，而且重新加入时可以直接
-- 清除 `left_at` 而不是新建一行。
--
-- ⚠️ **于是 `book_members` 的行有两层含义**，读的时候要分清：
--   * 行存在                = 这个账号**曾经**与这本账有过关系（历史）
--   * `left_at IS NULL`     = 他**现在**是成员（权限判断只看这个）
-- 这与 `transactions` 用 `deleted_at` 表达墓碑是同一种做法——**保留行、用一个时间戳改变含义**。

ALTER TABLE "book_members"
  ADD COLUMN IF NOT EXISTS "left_at" TIMESTAMPTZ(6);

-- 权限判断每次都要问"这个人在不在本账、什么角色"，所以要有这个索引。
CREATE INDEX IF NOT EXISTS "book_members_book_id_left_at_idx"
  ON "book_members"("book_id", "left_at");

-- ---------------------------------------------------------------------------
-- 4. ⚠️ 把现有的 `owner` 全部改成 `editor`
-- ---------------------------------------------------------------------------
--
-- **这是这个迁移里唯一改数据的语句，也是不运行它就会出错的一条。**
--
-- 背景：所有者决定**取消 owner，只保留 editor / viewer**。
-- 而现有两行成员关系（naeor 的账本 40000000、mama 的 40000001）的 role 都是 `owner`：
-- 如果代码只认 editor/viewer，**这两本账会变成"没有任何可管理成员"**——
-- 没人能记账、没人能改权限，而且**修不回来**（因为改权限本身也需要 editor）。
--
-- 所有者对这一步的要求：**"创建者加入账本时必须显式授予 editor，
-- 所有现有 owner 数据也要在迁移时正确处理，避免出现账本没有任何可管理成员的情况。"**
--
-- ⚠️ 枚举值 `owner` 本身**不删**（删枚举值要改 DB 约束，收益为零）；
-- 代码从此不再产生它、也不再认它——**旧值必须在数据层清掉**。

UPDATE "book_members" SET "role" = 'editor' WHERE "role" = 'owner';

-- ---------------------------------------------------------------------------
-- 5. `BookMember.role` 的默认值：owner → viewer
-- ---------------------------------------------------------------------------
--
-- 现状是 `@default(owner)`：**任何忘记显式传 role 的插入都会直接给出所有权**，
-- 那是一个迟早会出事的默认值。
--
-- ⚠️ **所有者对这一条的补充要求（必须照做）**：
-- "不能只修改默认值就算完成。创建者加入账本时必须**显式授予 editor**。"
-- 所以应用层的"新建账本"必须写出 `role: "editor"`，**不许依赖默认值**。
-- 默认值改成 viewer 之后，"忘传"的后果从"给出所有权"变成"给出只读"——安全方向。

ALTER TABLE "book_members" ALTER COLUMN "role" SET DEFAULT 'viewer';

-- ---------------------------------------------------------------------------
-- 6. ⚠️ 兜底：每本账至少有一个可管理的成员
-- ---------------------------------------------------------------------------
--
-- 第 4 步之后，理论上每本账都该有 editor。但**一个"理论上"是不够的**——
-- 如果某本账的成员行全是 viewer（或成员行被删空），它会变成**死账**：
-- 没人能记账，也没人能改回来，**而这是不可逆的**。
--
-- 所以这里做一次显式兜底：**谁创建的账本，就把创建者升成 editor**。
-- 依据是 `books.created_by`（创建者一定是当初的 owner，第 4 步把他降成了 editor，
-- 但如果那行丢了、或者历史上有别的怪状态，这一步会把他补回来）。
--
-- ⚠️ 插不进去就不插（`ON CONFLICT DO NOTHING`），绝不因为"补历史"而制造重复行。

INSERT INTO "book_members" ("book_id", "user_id", "role", "joined_at")
SELECT b."id", b."created_by", 'editor', CURRENT_TIMESTAMP
  FROM "books" b
 WHERE NOT EXISTS (
         SELECT 1 FROM "book_members" m
          WHERE m."book_id" = b."id"
            AND m."role" = 'editor'
            AND m."left_at" IS NULL
       )
ON CONFLICT ("book_id", "user_id") DO UPDATE SET "role" = 'editor', "left_at" = NULL;
