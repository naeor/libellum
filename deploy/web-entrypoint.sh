#!/bin/sh
#
# Render the real Caddyfile from the committed template, then exec Caddy.
#
# ⚠️ **Why this exists: the `email` directive cannot tolerate an empty value.**
#
# The template's global block wants to carry the ACME notification address:
#
#     email {$ACME_EMAIL:admin@libevra.com}
#
# and that fallback does **not** do what it looks like it does. Measured on a real Caddy
# (S12-B, 2026-10-16):
#
#   * `ACME_EMAIL` **unset**      -> the `:-` default applies -> config valid
#   * `ACME_EMAIL` **set, empty** -> expands to nothing -> `email` has no argument ->
#                                   **`adapting config using caddyfile: parsing caddyfile
#                                   tokens for 'email': wrong argument count`**
#
# Docker Compose passes `${ACME_EMAIL:-}` as an **empty but set** variable, so the second
# case is the one that happens in practice — and it is fatal: Caddy rejects the *whole*
# configuration, so the site does not come up at all. A missing notification address must
# not be able to stop the ledger from serving.
#
# ⚠️ **So the line is emitted only when there is a real address.** That is a conditional,
# and the Caddyfile format has no conditionals; a two-line shell script is the smallest
# honest way to express one. It runs once at container start.
#
# ⚠️ **The template is mounted read-only and never edited.** The rendered file goes to
# `/etc/caddy/Caddyfile`, which is a container path. `caddy validate` in the deploy
# runbook exercises the *template* with no `ACME_EMAIL` set, which is the "unset" case and
# therefore valid — this script is what covers the "set but empty" case at run time.
set -eu

TEMPLATE=/etc/caddy/Caddyfile.template
RENDERED=/etc/caddy/Caddyfile

if [ ! -f "$TEMPLATE" ]; then
	echo "libevra: $TEMPLATE is missing" >&2
	exit 1
fi

# The template marks the optional line with a sentinel comment so the marker can never
# collide with real Caddyfile syntax.
if [ -n "${ACME_EMAIL:-}" ]; then
	# A real address: keep the line, with the comment marker removed.
	sed 's|^[[:space:]]*#[[:space:]]*LIBEVRA_OPTIONAL_EMAIL[[:space:]]*$|	email '"$ACME_EMAIL"'|' \
		"$TEMPLATE" > "$RENDERED"
	echo "libevra: ACME account email set for $LIBEVRA_DOMAIN"
else
	# No address: drop the line entirely. Certificates are still issued and renewed;
	# only the expiry-warning emails are missing.
	grep -v 'LIBEVRA_OPTIONAL_EMAIL' "$TEMPLATE" > "$RENDERED"
	echo "libevra: no ACME account email configured - certificates will still be issued"
fi

# ⚠️ **`www` is served as a redirect to the apex, and only when the DNS for it exists.**
#
# The owner configured a `www` CNAME, so `https://www.libevra.com/` is reachable — but with
# no site block it matched no certificate and answered nothing (measured: `curl` exit 000,
# "no route"). Two URLs for one ledger is also how a session ends up looking logged-out.
#
# ⚠️ **It is probe-gated because requesting a certificate for a name whose DNS does not point
# here fails, and Let's Encrypt rate-limits failures per registered domain.** The probe is
# `getent hosts`, which asks the container's resolver — the same resolution Caddy's ACME
# client will use. If `www` does not resolve, the block is simply not emitted and nothing is
# attempted.
if getent hosts "www.$LIBEVRA_DOMAIN" >/dev/null 2>&1; then
	cat >> "$RENDERED" <<EOF

# ---- generated by web-entrypoint.sh: www -> apex ----
www.$LIBEVRA_DOMAIN {
	redir https://$LIBEVRA_DOMAIN{uri} permanent
}
EOF
	echo "libevra: www.$LIBEVRA_DOMAIN resolves - added a redirect to https://$LIBEVRA_DOMAIN"
else
	echo "libevra: www.$LIBEVRA_DOMAIN does not resolve - no www block added (no certificate attempted)"
fi

exec caddy run --config "$RENDERED" --adapter caddyfile
